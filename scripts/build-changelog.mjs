#!/usr/bin/env node
/**
 * 把根目录 CHANGELOG.md / CHANGELOG_EN.md 解析成渲染层可直接消费的结构化数据。
 *
 * 为什么是构建时生成而不是运行时读文件：
 * - 渲染层是 Next 静态导出，客户端组件拿不到 fs；
 * - 日志要离线可用，不依赖 GitHub / 更新服务；
 * - 数据随安装包发布，版本与日志永远对得上（升级后弹窗读的是包里这一份）。
 *
 * 输出：apps/desktop/lib/changelog/generated.ts（提交进仓库，保证 dev / typecheck
 * 不依赖预生成；改了 CHANGELOG 后跑 `bun run changelog`，`--check` 用于 CI 兜底）。
 *
 * 解析范围：只收正式版本节（`## [1.2.2] - 2026-11-21`），`[Unreleased]` 与
 * 文件头说明丢弃；`### Added/Changed/Fixed…` 原样保留标题，展示层再做本地化。
 * 中英两份必须版本一一对应，缺版本/多版本直接报错。
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_ZH = join(root, "CHANGELOG.md");
const SOURCE_EN = join(root, "CHANGELOG_EN.md");
const TARGET = join(root, "apps", "desktop", "lib", "changelog", "generated.ts");

const VERSION_HEADING = /^##\s+\[?v?(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\]?\s*(?:-\s*(.+?))?\s*$/;
const SECTION_HEADING = /^###\s+(.+?)\s*$/;
const BULLET = /^-\s+(.*)$/;
const CONTINUATION = /^\s{2,}(\S.*)$/;

/** CJK 字符与标点：折行拼接时按中文排版习惯决定要不要补空格 */
const CJK_LETTER = /[\u3400-\u9fff\uf900-\ufaff]/u;
const FULLWIDTH_PUNCT = /[\u3000-\u303f\uff00-\uffef]/u;
const DASH = /[—–]/u;

/**
 * CHANGELOG 按 80 列折行，换行处原本是 Markdown 软换行（渲染成一个空格）。
 * 直接补空格会让中文标点后多出空格（“输入， 并提示”），完全不补又会把
 * “为 macOS”粘成“为macOS”。这里按两侧字符决定：
 * - 任一侧是全角标点 → 不补（全角标点自带断句与间距）；
 * - 破折号后接中文 → 不补；接英文（英文日志的 “— compatible”）→ 补；
 * - 两侧都是中文 → 不补；
 * - 其余（中英混排、英文单词间）→ 补一个空格。
 */
function joinContinuation(previous, next) {
  const last = previous.slice(-1);
  const first = next.slice(0, 1);
  if (FULLWIDTH_PUNCT.test(last) || FULLWIDTH_PUNCT.test(first)) {
    return previous + next;
  }
  if (DASH.test(last)) {
    return CJK_LETTER.test(first) ? previous + next : `${previous} ${next}`;
  }
  if (DASH.test(first)) return previous + next;
  if (CJK_LETTER.test(last) && CJK_LETTER.test(first)) return previous + next;
  return `${previous} ${next}`;
}

/**
 * @typedef {{ title: string, items: string[] }} ChangelogSection
 * @typedef {{ version: string, date: string | null, intro: string | null, sections: ChangelogSection[] }} ChangelogEntry
 */

/** @param {string} markdown @returns {ChangelogEntry[]} */
export function parseChangelog(markdown) {
  /** @type {ChangelogEntry[]} */
  const entries = [];
  /** @type {ChangelogEntry | null} */
  let entry = null;
  /** @type {ChangelogSection | null} */
  let section = null;
  /** @type {string | null} 当前正在累积的列表项（支持缩进续行） */
  let item = null;
  /** @type {string[]} */
  let introLines = [];

  const commitItem = () => {
    if (item === null) return;
    const text = item.replace(/\s+$/u, "");
    if (text && section) section.items.push(text);
    item = null;
  };

  const commitIntro = () => {
    if (!entry) return;
    const text = introLines.join("\n").trim();
    entry.intro = text.length > 0 ? text : null;
    introLines = [];
  };

  for (const rawLine of markdown.replace(/\r\n?/gu, "\n").split("\n")) {
    const versionMatch = VERSION_HEADING.exec(rawLine);
    if (versionMatch) {
      commitItem();
      commitIntro();
      section = null;
      entry = {
        version: versionMatch[1],
        date: versionMatch[2]?.trim() || null,
        intro: null,
        sections: [],
      };
      entries.push(entry);
      continue;
    }
    // 其他二级标题（如 [Unreleased]）结束当前版本节
    if (/^##\s+/u.test(rawLine)) {
      commitItem();
      commitIntro();
      entry = null;
      section = null;
      continue;
    }
    if (!entry) continue;

    const sectionMatch = SECTION_HEADING.exec(rawLine);
    if (sectionMatch) {
      commitItem();
      section = { title: sectionMatch[1], items: [] };
      entry.sections.push(section);
      continue;
    }

    const bulletMatch = BULLET.exec(rawLine);
    if (bulletMatch) {
      commitItem();
      item = bulletMatch[1];
      continue;
    }

    // 缩进续行：并入当前条目（CHANGELOG 里长句按 80 列折行）
    const contMatch = CONTINUATION.exec(rawLine);
    if (contMatch) {
      if (item !== null) item = joinContinuation(item, contMatch[1]);
      else if (!section) introLines.push(contMatch[1]);
      continue;
    }

    if (rawLine.trim() === "") {
      commitItem();
      continue;
    }

    // 版本标题与第一个 ### 之间的导语（如“首个开源正式版。”）
    if (!section) introLines.push(rawLine.trim());
  }

  commitItem();
  commitIntro();
  return entries.filter((e) => e.sections.length > 0);
}

function renderModule(entriesZh, entriesEn) {
  const zh = JSON.stringify(entriesZh, null, 2);
  const en = JSON.stringify(entriesEn, null, 2);
  return `// AUTO-GENERATED by scripts/build-changelog.mjs — do not edit.
// Source: CHANGELOG.md / CHANGELOG_EN.md（改了它们之后跑 \`bun run changelog\`）
import type { ChangelogEntry } from "./types";

export const CHANGELOG_ENTRIES: readonly ChangelogEntry[] = ${zh};

export const CHANGELOG_ENTRIES_EN: readonly ChangelogEntry[] = ${en};
`;
}

function readSource(path, label) {
  try {
    return readFileSync(path, "utf8");
  } catch (err) {
    console.error(
      `✗ 读不到 ${label}（${path}）: ${err instanceof Error ? err.message : err}`,
    );
    process.exit(1);
  }
}

/** 中英版本号必须一一对应；顺序也要一致，避免界面切换语言时对不上版本 */
function assertSameVersions(zh, en) {
  const zhVersions = zh.map((e) => e.version);
  const enVersions = en.map((e) => e.version);
  if (zhVersions.join(",") !== enVersions.join(",")) {
    console.error(
      `✗ 中英更新日志版本不一致：\n  zh: ${zhVersions.join(", ")}\n  en: ${enVersions.join(", ")}`,
    );
    process.exit(1);
  }
}

function main() {
  const check = process.argv.includes("--check");
  const entriesZh = parseChangelog(readSource(SOURCE_ZH, "CHANGELOG.md"));
  const entriesEn = parseChangelog(readSource(SOURCE_EN, "CHANGELOG_EN.md"));
  if (entriesZh.length === 0 || entriesEn.length === 0) {
    console.error("✗ CHANGELOG 里没有解析到任何版本节");
    process.exit(1);
  }
  assertSameVersions(entriesZh, entriesEn);
  const output = renderModule(entriesZh, entriesEn);

  if (check) {
    let current = "";
    try {
      current = readFileSync(TARGET, "utf8");
    } catch {
      console.error(`✗ 缺少生成文件 ${TARGET}：先跑 \`bun run changelog\``);
      process.exit(1);
    }
    if (current !== output) {
      console.error(
        "✗ 更新日志生成文件与 CHANGELOG 不一致：跑 `bun run changelog` 后提交",
      );
      process.exit(1);
    }
    console.log(
      `✓ 更新日志已与 CHANGELOG 同步（zh/en 各 ${entriesZh.length} 个版本）`,
    );
    return;
  }

  writeFileSync(TARGET, output, "utf8");
  console.log(
    `✓ 更新日志：zh ${entriesZh.length} / en ${entriesEn.length} 个版本 → ${TARGET.slice(root.length + 1)}`,
  );
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) main();
